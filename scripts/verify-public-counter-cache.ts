import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { setTimeout as delay } from 'node:timers/promises'

import { Redis } from '@upstash/redis'

import { createPublicCounterCache } from '../src/features/pro/server/publicCounterCache'

// Only disposable Redis keys are used. This script never imports the DB client.
const url = process.env.UPSTASH_REDIS_REST_URL
const token = process.env.UPSTASH_REDIS_REST_TOKEN
if (!url || !token) throw new Error('Provide UPSTASH_REDIS_REST_URL and UPSTASH_REDIS_REST_TOKEN')
const client = () =>
  new Redis({
    url,
    token,
    retry: false,
    enableAutoPipelining: false,
    signal: () => AbortSignal.timeout(5000),
  })
const admin = client()
const prefix = `gitascii:test:public-counter:${randomUUID()}`
const keys = [`${prefix}:shared`, `${prefix}:outage`]
const ownedKeys = keys.flatMap((key) => [key, `${key}:refresh-budget`])
let sourceReads = 0

function worker(key: string, failWrites = false, refreshSeconds = 3600) {
  const connection = client()
  return createPublicCounterCache({
    key,
    refreshSeconds,
    load: async () => {
      sourceReads++
      return 426
    },
    valid: (value): value is number => typeof value === 'number' && value >= 0,
    fallback: () => 0,
    getStore: () => ({
      get: (cacheKey) => connection.get(cacheKey),
      set: (cacheKey, value, options) => {
        if (failWrites && !options.nx) return Promise.reject(new Error('Injected write failure'))
        return connection.set(cacheKey, value, options)
      },
    }),
  })
}

try {
  // Real NX arbitration across independent HTTP clients and cache instances.
  await Promise.all(Array.from({ length: 20 }, () => worker(keys[0])()))
  assert.equal(sourceReads, 1)
  assert.equal(await worker(keys[0])(), 426)
  const ttl = await admin.ttl(`${keys[0]}:refresh-budget`)
  assert.ok(ttl > 3500 && ttl <= 3600, 'Hourly reservation must remain after success')
  console.log('PASS: 20 independent Redis clients -> 1 source read; hourly reservation retained')

  // Shorten ONLY this test-owned reservation to test expiration without waiting an hour.
  await admin.expire(keys[0], 1)
  await admin.expire(`${keys[0]}:refresh-budget`, 1)
  await delay(1200)
  await Promise.all(Array.from({ length: 20 }, () => worker(keys[0])()))
  assert.equal(sourceReads, 2)
  console.log('PASS: real Redis expiration -> exactly 1 additional source read')

  await worker(keys[1], true)()
  assert.equal(sourceReads, 3)
  await Promise.all(Array.from({ length: 20 }, () => worker(keys[1], true)()))
  assert.equal(sourceReads, 3)
  console.log('PASS: failed snapshot persistence -> no repeated source reads across clients')
} finally {
  // Only exact keys generated by this run; never SCAN/FLUSH or application keys.
  await admin.del(...ownedKeys)
  console.log('Removed disposable test keys. Postgres was not accessed.')
}
